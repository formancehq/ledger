func metadataScriptOrder(script string) *raftcmdpb.Order {
	return requestToOrder(&servicepb.Request{Type: &servicepb.Request_Apply{Apply: &servicepb.LedgerApplyRequest{
		Ledger: "test-ledger",
		Action: &servicepb.LedgerAction{Data: &servicepb.LedgerAction_CreateTransaction{CreateTransaction: &servicepb.CreateTransactionPayload{
			Script: &commonpb.Script{Plain: script + `
    send [USD/2 100] (source = @world destination = @users:alice)
   `},
		}}},
	}}})
}

func metadataCommandScope(t *testing.T, ctrl *gomock.Controller) *MockScope {
	t.Helper()
	scope := NewMockScope(ctrl)
	policy := tightMetadataPolicy(10)
	policy.MetadataMaxKeyBytes = 10
	scope.EXPECT().GetClusterPolicy().Return(policy).AnyTimes()
	scope.EXPECT().GetDate().Return((&commonpb.Timestamp{Data: 1234567890}).AsReader()).AnyTimes()
	scope.EXPECT().GetNextSequenceID().Return(uint64(1)).AnyTimes()
	scope.EXPECT().IncrementNextSequenceID().Return(uint64(1), nil).AnyTimes()
	boundaries := &raftcmdpb.LedgerBoundaries{NextTransactionId: 1, NextLogId: 1}
	boundaryStub := setupBoundariesStub(scope)
	boundaryStub.onGet(func(domain.LedgerKey) (raftcmdpb.LedgerBoundariesReader, error) {
		return boundaries.AsReader(), nil
	})
	boundaryStub.onPut(func(_ domain.LedgerKey, value *raftcmdpb.LedgerBoundaries) { boundaries = value })
	expectGetLedger(scope, domain.LedgerKey{Name: "test-ledger"}, (&commonpb.LedgerInfo{Name: "test-ledger", Id: 1}).AsReader(), nil).AnyTimes()
	setupNumscriptVolumeMocks(scope)
	_, _ = stubsFor(scope).transactionStatesStubFor(scope)
	_, _ = stubsFor(scope).accountMetadataStubFor(scope)

	return scope
}

func TestProcessOrders_NumscriptCommandMetadataCeiling(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name      string
		orders    func() []*raftcmdpb.Order
		completed int
	}{
		{name: "multiple accounts", orders: func() []*raftcmdpb.Order {
			return []*raftcmdpb.Order{metadataScriptOrder(`set_account_meta(@users:alice, "k", "12345")
    set_account_meta(@users:bob, "k", "12345")`)}
		}},
		{name: "transaction plus account", orders: func() []*raftcmdpb.Order {
			return []*raftcmdpb.Order{metadataScriptOrder(`set_tx_meta("k", "12345")
    set_account_meta(@users:alice, "k", "12345")`)}
		}},
		{name: "multiple scripts", completed: 1, orders: func() []*raftcmdpb.Order {
			return []*raftcmdpb.Order{metadataScriptOrder(`set_tx_meta("k", "12345")`), metadataScriptOrder(`set_tx_meta("k", "12345")`)}
		}},
		{name: "later caller metadata", orders: func() []*raftcmdpb.Order {
			later := requestToOrder(&servicepb.Request{Type: &servicepb.Request_Apply{Apply: &servicepb.LedgerApplyRequest{
				Ledger: "test-ledger", Action: &servicepb.LedgerAction{Data: &servicepb.LedgerAction_AddMetadata{AddMetadata: &commonpb.SaveMetadataCommand{
					Target:   &commonpb.Target{Target: &commonpb.Target_Account{Account: &commonpb.TargetAccount{Addr: "users:bob"}}},
					Metadata: map[string]*commonpb.MetadataValue{"k": commonpb.NewStringValue("12345")},
				}}},
			}}})

			return []*raftcmdpb.Order{metadataScriptOrder(`set_tx_meta("k", "12345")`), later}
		}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			ctrl := gomock.NewController(t)
			scope := metadataCommandScope(t, ctrl)
			sink := NewMockSignalSink(ctrl)
			sink.EXPECT().Absorb(gomock.Any(), gomock.Any()).Times(tc.completed)
			processor, err := NewRequestProcessor(nil, 0)
			require.NoError(t, err)
			result, procErr := processor.ProcessOrders(tc.orders(), mockFactory(scope), sink)
			require.Nil(t, result)
			require.NotNil(t, procErr)
			require.Equal(t, domain.ErrReasonMetadataLimitExceeded, procErr.Reason())
			require.Equal(t, domain.MetadataLimitDimensionCommand, procErr.Metadata()["dimension"])
			require.Equal(t, "12", procErr.Metadata()["actual"])
			require.Equal(t, "10", procErr.Metadata()["limit"])
		})
	}
}

func TestProcessOrders_NumscriptCommandMetadataBoundaryAndReset(t *testing.T) {
	t.Parallel()
	ctrl := gomock.NewController(t)
	scope := metadataCommandScope(t, ctrl)
	processor, err := NewRequestProcessor(nil, 0)
	require.NoError(t, err)
	order := metadataScriptOrder(`set_tx_meta("k", "1234")
  set_account_meta(@users:alice, "k", "1234")`)
	// Each fresh proposal fits exactly. Reusing the processor must not retain the
	// preceding proposal's generated bytes.
	for range 2 {
		result, procErr := processor.ProcessOrders([]*raftcmdpb.Order{order}, mockFactory(scope), noopSink{})
		require.Nil(t, procErr)
		require.Len(t, result.CreatedLogs, 1)
	}
}

func TestProcessOrders_NumscriptCommandMetadataCallerWins(t *testing.T) {
	t.Parallel()
	ctrl := gomock.NewController(t)
	scope := metadataCommandScope(t, ctrl)
	processor, err := NewRequestProcessor(nil, 0)
	require.NoError(t, err)
	order := metadataScriptOrder(`set_tx_meta("k", "overshadowed")
  set_account_meta(@users:alice, "k", "overshadowed")`)
	payload := order.GetLedgerScoped().GetApply().GetCreateTransaction()
	payload.Metadata = map[string]*commonpb.MetadataValue{"k": commonpb.NewStringValue("1234")}
	payload.AccountMetadata = map[string]*commonpb.MetadataMap{"users:alice": {Values: map[string]*commonpb.MetadataValue{"k": commonpb.NewStringValue("1234")}}}
	before := order.CloneVT()
	result, procErr := processor.ProcessOrders([]*raftcmdpb.Order{order}, mockFactory(scope), noopSink{})
	require.Nil(t, procErr)
	require.Len(t, result.CreatedLogs, 1)
	created := result.CreatedLogs[0].GetPayload().GetApply().GetLog().GetData().GetCreatedTransaction()
	require.Equal(t, "1234", created.GetTransaction().GetMetadata()["k"].GetStringValue())
	require.Equal(t, "1234", created.GetAccountMetadata()["users:alice"].GetValues()["k"].GetStringValue())
	require.True(t, before.EqualVT(order), "script merge must not mutate the accepted order")
}

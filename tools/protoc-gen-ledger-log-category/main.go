// protoc-gen-ledger-log-category generates the exhaustive HISTORY/CONTROL
// classifier for common.LedgerLogPayload. Every oneof arm must carry an
// explicit common.ledger_log_is_history field option; generation fails
// when a new payload is added without an explicit classification.
package main

import (
	"fmt"
	"slices"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"
	"google.golang.org/protobuf/types/dynamicpb"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	payloadMessage    = "common.LedgerLogPayload"
	payloadOneof      = "payload"
	categoryExtension = "common.ledger_log_is_history"
)

type payloadArm struct {
	goOneofWrapper string
	isHistory      bool
}

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)

		extDesc := findExtension(gen, categoryExtension)
		if extDesc == nil {
			return fmt.Errorf("extension %q not found in compiled protos", categoryExtension)
		}

		extType := dynamicpb.NewExtensionType(extDesc)
		resolver := &protoregistry.Types{}
		if err := resolver.RegisterExtension(extType); err != nil {
			return fmt.Errorf("registering %q extension type: %w", categoryExtension, err)
		}

		msg := findMessage(gen, payloadMessage)
		if msg == nil {
			return fmt.Errorf("message %q not found in compiled protos", payloadMessage)
		}

		targetFile := fileOf(gen, msg)
		if targetFile == nil {
			return fmt.Errorf("could not locate the generated file for %q", payloadMessage)
		}

		arms, err := collectArms(msg, extType, resolver)
		if err != nil {
			return err
		}

		generate(gen, targetFile, arms)

		return nil
	})
}

func findExtension(gen *protogen.Plugin, fullName string) protoreflect.ExtensionDescriptor {
	for _, file := range gen.Files {
		for _, ext := range file.Extensions {
			if string(ext.Desc.FullName()) == fullName {
				return ext.Desc
			}
		}
	}

	return nil
}

func findMessage(gen *protogen.Plugin, fullName string) *protogen.Message {
	for _, file := range gen.Files {
		for _, msg := range file.Messages {
			if string(msg.Desc.FullName()) == fullName {
				return msg
			}
		}
	}

	return nil
}

func fileOf(gen *protogen.Plugin, msg *protogen.Message) *protogen.File {
	for _, file := range gen.Files {
		if slices.Contains(file.Messages, msg) {
			return file
		}
	}

	return nil
}

func collectArms(msg *protogen.Message, extType protoreflect.ExtensionType, resolver *protoregistry.Types) ([]payloadArm, error) {
	var oneof *protogen.Oneof
	for _, candidate := range msg.Oneofs {
		if string(candidate.Desc.Name()) == payloadOneof {
			oneof = candidate

			break
		}
	}
	if oneof == nil {
		return nil, fmt.Errorf("oneof %q not found on %q", payloadOneof, payloadMessage)
	}

	arms := make([]payloadArm, 0, len(oneof.Fields))
	for _, field := range oneof.Fields {
		isHistory, present, err := readCategory(field, extType, resolver)
		if err != nil {
			return nil, err
		}
		if !present {
			return nil, fmt.Errorf("LedgerLogPayload oneof arm %q has no explicit ledger_log_is_history annotation", field.Desc.Name())
		}

		arms = append(arms, payloadArm{
			goOneofWrapper: field.GoIdent.GoName,
			isHistory:      isHistory,
		})
	}

	return arms, nil
}

func readCategory(field *protogen.Field, extType protoreflect.ExtensionType, resolver *protoregistry.Types) (bool, bool, error) {
	opts := field.Desc.Options()
	if opts == nil {
		return false, false, nil
	}

	raw, err := proto.Marshal(opts)
	if err != nil {
		return false, false, fmt.Errorf("marshaling options for %q: %w", field.Desc.FullName(), err)
	}

	resolved := dynamicpb.NewMessage(opts.ProtoReflect().Descriptor())
	if err := (proto.UnmarshalOptions{Resolver: resolver}).Unmarshal(raw, resolved); err != nil {
		return false, false, fmt.Errorf("re-parsing options for %q: %w", field.Desc.FullName(), err)
	}

	desc := extType.TypeDescriptor()
	if !resolved.Has(desc) {
		return false, false, nil
	}

	return resolved.Get(desc).Bool(), true, nil
}

func generate(gen *protogen.Plugin, file *protogen.File, arms []payloadArm) {
	g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_ledger_log_category.pb.go", file.GoImportPath)

	g.P("// Code generated by protoc-gen-ledger-log-category. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P("//")
	g.P("// Exhaustive LedgerLogPayload HISTORY/CONTROL classification (EN-1771).")
	g.P("// Edit common.ledger_log_is_history annotations and run `just generate-proto`.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	g.P("// LedgerLogCategory is the generated, build-enforced business-history class.")
	g.P("type LedgerLogCategory uint8")
	g.P()
	g.P("const (")
	g.P("LedgerLogCategory_LEDGER_LOG_CATEGORY_UNSPECIFIED LedgerLogCategory = iota")
	g.P("LedgerLogCategory_LEDGER_LOG_CATEGORY_CONTROL")
	g.P("LedgerLogCategory_LEDGER_LOG_CATEGORY_HISTORY")
	g.P(")")
	g.P()
	g.P("// LedgerLogCategoryOf returns the protobuf-declared category of payload.")
	g.P("// Nil and unknown payloads return LEDGER_LOG_CATEGORY_UNSPECIFIED so callers")
	g.P("// can surface malformed or forward-incompatible input as an invariant error.")
	g.P("func LedgerLogCategoryOf(payload *LedgerLogPayload) LedgerLogCategory {")
	g.P("if payload == nil {")
	g.P("return LedgerLogCategory_LEDGER_LOG_CATEGORY_UNSPECIFIED")
	g.P("}")
	g.P()
	g.P("switch payload.GetPayload().(type) {")
	for _, arm := range arms {
		g.P("case *", arm.goOneofWrapper, ":")
		if arm.isHistory {
			g.P("return LedgerLogCategory_LEDGER_LOG_CATEGORY_HISTORY")
		} else {
			g.P("return LedgerLogCategory_LEDGER_LOG_CATEGORY_CONTROL")
		}
	}
	g.P("default:")
	g.P("return LedgerLogCategory_LEDGER_LOG_CATEGORY_UNSPECIFIED")
	g.P("}")
	g.P("}")
	g.P()
	g.P("// IsLedgerHistoryPayload reports whether payload contributes business history.")
	g.P("func IsLedgerHistoryPayload(payload *LedgerLogPayload) bool {")
	g.P("return LedgerLogCategoryOf(payload) == LedgerLogCategory_LEDGER_LOG_CATEGORY_HISTORY")
	g.P("}")
}

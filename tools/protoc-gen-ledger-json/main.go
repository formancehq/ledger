// protoc-gen-ledger-json generates standard-library JSON marshalers for the
// public protobuf messages selected by the Ledger JSON projection policy.
package main

import (
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/encoding/protowire"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

const ledgerJSONOptionNumber = protowire.Number(71003)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, file := range gen.Files {
			if !file.Generate {
				continue
			}

			var messages []*protogen.Message
			for _, message := range file.Messages {
				collectMessages(message, &messages)
			}
			selectedMessages := make([]*protogen.Message, 0, len(messages))
			for _, message := range messages {
				if selected(message) {
					selectedMessages = append(selectedMessages, message)
				}
			}
			if len(selectedMessages) == 0 {
				continue
			}

			g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_ledger_json.pb.go", file.GoImportPath)
			g.P("// Code generated by protoc-gen-ledger-json. DO NOT EDIT.")
			g.P("// source: ", file.Desc.Path())
			g.P()
			g.P("package ", file.GoPackageName)
			g.P()
			g.P(`import jsonv2 "encoding/json/v2"`)
			g.P()
			for _, message := range selectedMessages {
				emitMessage(g, message)
			}
		}
		return nil
	})
}


// protoc-gen-ledger-json generates standard-library JSON marshalers for the
// public protobuf messages selected by the Ledger JSON projection policy.
package main

import (
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/encoding/protowire"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

const ledgerJSONOptionNumber = protowire.Number(71003)
const ledgerJSONDefaultOptionNumber = protowire.Number(71004)
const ledgerJSONManualOptionNumber = protowire.Number(71005)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, file := range gen.Files {
			if !file.Generate {
				continue
			}

			var messages []*protogen.Message
			for _, message := range file.Messages {
				collectMessages(message, &messages)
			}
			selectedMessages := make([]*protogen.Message, 0, len(messages))
			for _, message := range messages {
				if selected(file, message) {
					selectedMessages = append(selectedMessages, message)
				}
			}
			if len(selectedMessages) == 0 {
				continue
			}

			g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_ledger_json.pb.go", file.GoImportPath)
			g.P("// Code generated by protoc-gen-ledger-json. DO NOT EDIT.")
			g.P("// source: ", file.Desc.Path())
			g.P()
			g.P("package ", file.GoPackageName)
			g.P()
			g.P(`import jsonv2 "encoding/json/v2"`)
			g.P()
			for _, message := range selectedMessages {
				emitMessage(g, message)
			}
		}
		return nil
	})
}

func emitMessage(g *protogen.GeneratedFile, message *protogen.Message) {
	g.P("func (x *", message.GoIdent.GoName, ") MarshalJSON() ([]byte, error) {")
	var oneof *protogen.Oneof
	for _, field := range message.Fields {
		if field.Oneof != nil && !field.Oneof.Desc.IsSynthetic() {
			oneof = field.Oneof
			break
		}
	}
	if oneof == nil {
		emitStructReturn(g, message, nil, nil)
	} else {
		g.P("\tswitch oneofValue := x.", oneof.GoName, ".(type) {")
		for _, field := range oneof.Fields {
			g.P("\tcase *", field.GoIdent.GoName, ":")
			emitStructReturn(g, message, oneof, field)
		}
		g.P("\tdefault:")
		emitStructReturn(g, message, oneof, nil)
		g.P("\t}")
	}
	g.P("}")
	g.P()
}

func emitStructReturn(g *protogen.GeneratedFile, message *protogen.Message, oneof *protogen.Oneof, selected *protogen.Field) {
	g.P("\t\treturn jsonv2.Marshal(struct {")
	for _, field := range message.Fields {
		if field.Oneof != nil && !field.Oneof.Desc.IsSynthetic() {
			if selected == nil || field != selected {
				continue
			}
			g.P("\t\t\t", field.GoName, " ", goJSONType(field.Desc, true), " `json:\"", field.Desc.JSONName(), "\"`")
			continue
		}
		tag := "json:\"" + field.Desc.JSONName() + "\""
		if field.Desc.HasPresence() {
			tag = "json:\"" + field.Desc.JSONName() + ",omitempty,omitzero\""
		}
		g.P("\t\t\t", field.GoName, " ", goJSONType(field.Desc, false), " `", tag, "`")
	}
	g.P("\t\t}{")
	for _, field := range message.Fields {
		if field.Oneof != nil && !field.Oneof.Desc.IsSynthetic() {
			if selected == nil || field != selected {
				continue
			}
			g.P("\t\t\t", field.GoName, ": ", jsonAssignment(g, "oneofValue."+field.GoName, field), ",")
			continue
		}
		g.P("\t\t\t", field.GoName, ": ", jsonAssignment(g, "x."+field.GoName, field), ",")
	}
	g.P("\t\t})")
}

func goJSONType(field protoreflect.FieldDescriptor, oneof bool) string {
	if field.IsList() || field.IsMap() || field.Message() != nil {
		return "any"
	}
	if field.HasPresence() && !oneof {
		switch field.Kind() {
		case protoreflect.BoolKind:
			return "*bool"
		case protoreflect.StringKind:
			return "*string"
		case protoreflect.BytesKind:
			return "*[]byte"
		case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
			return "*int32"
		case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
			return "*int64"
		case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
			return "*uint32"
		case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
			return "*uint64"
		case protoreflect.FloatKind:
			return "*float32"
		case protoreflect.DoubleKind:
			return "*float64"
		}
	}
	switch field.Kind() {
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BytesKind:
		return "[]byte"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	case protoreflect.FloatKind:
		return "float32"
	case protoreflect.DoubleKind:
		return "float64"
	case protoreflect.EnumKind:
		return "any"
	default:
		return "any"
	}
}

func jsonAssignment(g *protogen.GeneratedFile, access string, field *protogen.Field) string {
	if field.Desc.IsList() {
		if field.Desc.Kind() == protoreflect.EnumKind {
			return listEnumJSONAssignment(g, access, field)
		}
		return "func() any { if " + access + " == nil { return []any{} }; return " + access + " }()"
	}
	if field.Desc.IsMap() {
		return "func() any { if " + access + " == nil { return map[string]any{} }; return " + access + " }()"
	}
	if field.Desc.Kind() == protoreflect.EnumKind {
		return enumJSONAssignment(g, access, field)
	}
	return access
}

func listEnumJSONAssignment(g *protogen.GeneratedFile, access string, field *protogen.Field) string {
	expression := "func() any { if " + access + " == nil { return []any{} }; out := make([]any, len(" + access + ")); for i := range " + access + " { out[i] = "
	expression += enumJSONAssignment(g, access+"[i]", field)
	return expression + "; }; return out }()"
}

func enumJSONAssignment(g *protogen.GeneratedFile, access string, field *protogen.Field) string {
	values := field.Desc.Enum().Values()
	expression := "func() any {"
	expression += " switch " + access + " {"
	for i := 0; i < values.Len(); i++ {
		value := values.Get(i)
		expression += " case " + g.QualifiedGoIdent(field.Enum.Values[i].GoIdent) + ": return \"" + string(value.Name()) + "\";"
	}
	expression += " default: return int32(" + access + "); } }()"
	return expression
}

func collectMessages(message *protogen.Message, out *[]*protogen.Message) {
	*out = append(*out, message)
	for _, nested := range message.Messages {
		collectMessages(nested, out)
	}
}

func selected(file *protogen.File, message *protogen.Message) bool {
	if message.Desc.IsMapEntry() {
		return false
	}
	options := message.Desc.Options()
	if options == nil {
		return false
	}
	unknown := options.ProtoReflect().GetUnknown()
	for len(unknown) > 0 {
		number, typ, tagSize := protowire.ConsumeTag(unknown)
		if tagSize < 0 {
			return false
		}
		if number == ledgerJSONManualOptionNumber && typ == protowire.VarintType {
			return false
		}
		valueSize := protowire.ConsumeFieldValue(number, typ, unknown[tagSize:])
		if valueSize < 0 {
			return false
		}
		unknown = unknown[tagSize+valueSize:]
	}
	if fileDefault(file) {
		return true
	}
	unknown = options.ProtoReflect().GetUnknown()
	for len(unknown) > 0 {
		number, typ, tagSize := protowire.ConsumeTag(unknown)
		if tagSize < 0 {
			return false
		}
		if number == ledgerJSONOptionNumber && typ == protowire.VarintType {
			value, valueSize := protowire.ConsumeVarint(unknown[tagSize:])
			return valueSize >= 0 && value != 0
		}
		valueSize := protowire.ConsumeFieldValue(number, typ, unknown[tagSize:])
		if valueSize < 0 {
			return false
		}
		unknown = unknown[tagSize+valueSize:]
	}
	return false
}

func fileDefault(file *protogen.File) bool {
	options := file.Desc.Options()
	if options == nil {
		return false
	}
	unknown := options.ProtoReflect().GetUnknown()
	for len(unknown) > 0 {
		number, typ, tagSize := protowire.ConsumeTag(unknown)
		if tagSize < 0 {
			return false
		}
		if number == ledgerJSONDefaultOptionNumber && typ == protowire.VarintType {
			value, valueSize := protowire.ConsumeVarint(unknown[tagSize:])
			return valueSize >= 0 && value != 0
		}
		valueSize := protowire.ConsumeFieldValue(number, typ, unknown[tagSize:])
		if valueSize < 0 {
			return false
		}
		unknown = unknown[tagSize+valueSize:]
	}
	return false
}

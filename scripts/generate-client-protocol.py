#!/usr/bin/env python3
"""Generate the public client's protocol metadata from the server revision."""

import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
protocol = (root / "pkg/grpcprotocol/protocol.go").read_text()
match = re.search(r'\bVersion\s*=\s*"(\d+)"', protocol)
if match is None:
    raise SystemExit("server protocol revision is missing")

(root / "pkg/client/v3/grpc/protocol.go").write_text('''// Code generated by scripts/generate-client-protocol.py. DO NOT EDIT.
package grpc

import (
    "context"

    ggrpc "google.golang.org/grpc"
)

// ProtocolVersion is the Ledger service protocol revision implemented by this client.
const ProtocolVersion = "''' + match.group(1) + '''"

// ProtocolMetadataKey carries the compiled revision on every business RPC.
const ProtocolMetadataKey = "ledger-protocol-version"

// ClientOption declares this client's protocol revision for unary and streaming RPCs.
func ClientOption() ggrpc.DialOption {
    return ggrpc.WithPerRPCCredentials(protocolCredentials{})
}

type protocolCredentials struct{}

func (protocolCredentials) GetRequestMetadata(context.Context, ...string) (map[string]string, error) {
    return map[string]string{ProtocolMetadataKey: ProtocolVersion}, nil
}

func (protocolCredentials) RequireTransportSecurity() bool { return false }
''')

# Keep the historical client package as a source-compatible facade over the
# shared protobuf module. The generated message descriptors must have a single
# owner; aliases preserve the old import path without registering a second
# copy of those descriptors.
shared_dir = root / "pkg/proto/v3/ledgerpb"
types: set[str] = set()
constants: set[str] = set()
variables: set[str] = set()

for generated in shared_dir.glob("*.pb.go"):
    if generated.name.endswith("_grpc.pb.go"):
        continue
    in_const_block = False
    in_var_block = False
    for line in generated.read_text().splitlines():
        type_match = re.match(r"^type ([A-Z][A-Za-z0-9_]*)\b", line)
        if type_match:
            types.add(type_match.group(1))

        stripped = line.strip()
        if stripped == "const (":
            in_const_block = True
            continue
        if stripped == "var (":
            in_var_block = True
            continue
        if stripped == ")":
            in_const_block = False
            in_var_block = False
            continue

        declaration = re.match(r"^(?:const|var) ([A-Z][A-Za-z0-9_]*)\b", stripped)
        if declaration:
            (constants if stripped.startswith("const ") else variables).add(declaration.group(1))
        elif in_const_block:
            block_declaration = re.match(r"^([A-Z][A-Za-z0-9_]*)\b", stripped)
            if block_declaration:
                constants.add(block_declaration.group(1))
        elif in_var_block:
            block_declaration = re.match(r"^([A-Z][A-Za-z0-9_]*)\s+(?:[A-Za-z0-9_.]+\s+)?=", stripped)
            if block_declaration:
                variables.add(block_declaration.group(1))

aliases = [
    "// Code generated by scripts/generate-client-protocol.py. DO NOT EDIT.",
    "package grpc",
    "",
    'import ledgerpb "github.com/formancehq/ledger/pkg/proto/v3/ledgerpb"',
    "",
]
aliases.extend(f"type {name} = ledgerpb.{name}" for name in sorted(types))
aliases.append("")
aliases.extend(f"const {name} = ledgerpb.{name}" for name in sorted(constants))
aliases.append("")
aliases.extend(f"var {name} = ledgerpb.{name}" for name in sorted(variables))
aliases.append("")
(root / "pkg/client/v3/grpc/aliases.go").write_text("\n".join(aliases))

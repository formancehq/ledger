#!/usr/bin/env python3
"""Refresh the deterministic descriptor digest and protocol revision."""

import hashlib
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
client = root / "pkg/client/v3"
manifest = client / "contract.json"
data = json.loads(manifest.read_text())
assert data["clientModule"] == "github.com/formancehq/ledger/pkg/client/v3"
assert re.fullmatch(r"v3\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?", data["clientVersion"])
assert data["compatibleServerVersions"], "at least one tested server version is required"
assert all(re.fullmatch(r"v3\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?", v)
           for v in data["compatibleServerVersions"])

data["contractDescriptorSHA256"] = hashlib.sha256(
    (client / "proto/ledger-public.protoset").read_bytes()
).hexdigest()
protocol = (root / "pkg/grpcprotocol/protocol.go").read_text()
data["protocolVersion"] = re.search(r'\bVersion\s*=\s*"(\d+)"', protocol).group(1)
manifest.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
(client / "grpc/protocol.go").write_text('''// Code generated by scripts/update-client-contract.py. DO NOT EDIT.
package grpc

import (
    "context"

    ggrpc "google.golang.org/grpc"
)

// ProtocolVersion is the Ledger service protocol revision implemented by this client.
const ProtocolVersion = "''' + data["protocolVersion"] + '''"

// ProtocolMetadataKey carries the compiled revision on every business RPC.
const ProtocolMetadataKey = "ledger-protocol-version"

// ClientOption declares this client's protocol revision for unary and streaming RPCs.
func ClientOption() ggrpc.DialOption {
    return ggrpc.WithPerRPCCredentials(protocolCredentials{})
}

type protocolCredentials struct{}

func (protocolCredentials) GetRequestMetadata(context.Context, ...string) (map[string]string, error) {
    return map[string]string{ProtocolMetadataKey: ProtocolVersion}, nil
}

func (protocolCredentials) RequireTransportSecurity() bool { return false }
''')
